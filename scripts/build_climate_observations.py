SCORED_START, SCORED_END = 1990, 2023


def _here(*parts: str) -> str:
    return os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", *parts))


def write_emissions_csv() -> str:
    out = _here("data", "global_co2_emissions_owid.csv")
    with open(out, "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["year", "emissions_gtco2"])
        for year in sorted(_EMISSIONS_TONNES):
            w.writerow([year, f"{_EMISSIONS_TONNES[year] / 1e9:.6f}"])
    return out


def write_observations_json() -> str:
    out = _here("tests", "fixtures", "climate_observations_1990_2023.json")
    years = list(range(SCORED_START, SCORED_END + 1))
    data = {
        "start_year": SCORED_START,
        "end_year": SCORED_END,
        "spinup_start_year": min(_EMISSIONS_TONNES),
        "emissions_gtco2": {str(y): _EMISSIONS_TONNES[y] / 1e9 for y in years},
        "atmospheric_co2_ppm": {str(y): _CO2_PPM[y] for y in years},
        "temperature_c_preindustrial": {str(y): _HADCRUT_NATIVE[y] + _PREINDUSTRIAL_OFFSET for y in years},
        "source_notes": {
            "emissions_gtco2": "GCB fossil+cement CO2, World, via OWID OWID_WRL (full 1750-2024 in data/global_co2_emissions_owid.csv).",
            "atmospheric_co2_ppm": "NOAA GML global annual mean CO2 (co2_annmean_gl.txt).",
            "temperature_c_preindustrial": (
                "HadCRUT.5.1.0.0 global annual anomaly rebased to 1850-1900 by adding "
                f"{_PREINDUSTRIAL_OFFSET} (fixed to reproduce the legacy 2015-2023 fixture)."
            ),
        },
    }
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2)
        fh.write("\n")
    return out


def main() -> None:
    c = write_emissions_csv()
    j = write_observations_json()
    print(f"wrote {c}  ({len(_EMISSIONS_TONNES)} years)")
    print(f"wrote {j}  ({SCORED_END - SCORED_START + 1} scored years)")


if __name__ == "__main__":
    main()
